// Precompute the landing page's dotted world map, so browsers don't have to.
//
// svg-dotted-map tests thousands of sample points against every country's outline. Done in the browser
// on each render, that blocked the main thread for seconds. The map never changes, so it is computed here
// once and saved as one SVG path plus each city's position.
//
// Run after changing the map's size, sample count or the cities in map-data.ts:  npm run map:dots
import { readFileSync, writeFileSync } from "node:fs";
import { createMap } from "svg-dotted-map";

const WIDTH = 150;
const HEIGHT = 75;
const SAMPLES = 3800;
const DOT_RADIUS = 0.24;
const OUT = "src/components/marketing/world-dots.ts";

const round = (n) => Math.round(n * 100) / 100;

// The cities come from map-data.ts, so the two can't drift apart.
const source = readFileSync("src/components/marketing/map-data.ts", "utf8");
const cities = [...source.matchAll(/city: "([^"]+)", lat: (-?[\d.]+), lng: (-?[\d.]+)/g)].map(([, city, lat, lng]) => ({
  city,
  lat: Number(lat),
  lng: Number(lng),
}));
if (!cities.length) throw new Error("No cities found in map-data.ts");

const { points, addMarkers } = createMap({ width: WIDTH, height: HEIGHT, mapSamples: SAMPLES });

// Every other row is shifted half a step, as the Magic UI DottedMap does ("stagger").
const rows = [...new Set(points.map((p) => p.y))].sort((a, b) => a - b);
const rowIndex = new Map(rows.map((y, i) => [y, i]));
let step = 0;
const sorted = [...points].sort((a, b) => a.y - b.y || a.x - b.x);
for (let i = 1; i < sorted.length; i++) {
  if (sorted[i].y !== sorted[i - 1].y) continue;
  const d = sorted[i].x - sorted[i - 1].x;
  if (d > 0) step = step === 0 ? d : Math.min(step, d);
}
const xStep = step || 1;
const offset = (y) => ((rowIndex.get(y) ?? 0) % 2 === 1 ? xStep / 2 : 0);

// One path of tiny circles: far lighter for the browser than a thousand <circle> elements.
const r = DOT_RADIUS;
const path = points
  .map((p) => {
    const x = round(p.x + offset(p.y) - r);
    return `M${x} ${round(p.y)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
  })
  .join("");

const markers = Object.fromEntries(
  addMarkers(cities).map((m) => [m.city, { x: round(m.x + offset(m.y)), y: round(m.y) }]),
);

writeFileSync(
  OUT,
  `// Generated by scripts/world-dots.mjs (npm run map:dots). Do not edit by hand.
// ${points.length} dots, ${WIDTH}x${HEIGHT}, ${SAMPLES} samples.

export const WORLD_WIDTH = ${WIDTH};
export const WORLD_HEIGHT = ${HEIGHT};
export const WORLD_DOTS_PATH =
  ${JSON.stringify(path)};
export const CITY_POSITIONS: Record<string, { x: number; y: number }> = ${JSON.stringify(markers, null, 2)};
`,
);
console.log(`Wrote ${OUT}: ${points.length} dots, ${cities.length} cities, ${(path.length / 1024).toFixed(1)} KB path`);
